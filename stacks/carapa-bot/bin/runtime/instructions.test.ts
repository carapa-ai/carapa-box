import { afterEach, describe, expect, test } from 'bun:test';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  realpathSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import type { RunContext } from './contracts';
import { spawnSync } from 'node:child_process';
import {
  claudeGroupRulesFile,
  claudeModelDecisionFiles,
  ensureAgentSkillLinks,
  generateAgentOverrides,
  generateOmpAlwaysRule,
} from './instructions';

const roots: string[] = [];

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

function fixture(): RunContext {
  const root = mkdtempSync(join(tmpdir(), 'carapa-instructions-'));
  roots.push(root);
  const home = join(root, 'home');
  const cwd = join(root, 'work');
  mkdirSync(join(home, '.agent', 'rules'), { recursive: true });
  mkdirSync(join(cwd, '.agent', 'rules'), { recursive: true });
  return {
    runDir: join(root, 'run'),
    cwd,
    binDir: '/trusted/bin',
    prompt: '',
    runTag: 'run_',
    env: { HOME: home, CARAPA_GROUP_ROOT: join(root, 'group') },
    args: {
      agentCmd: 'pi', sessionId: '', forkSession: '', model: '', fallbackModel: '',
      reasoningEffort: '', fallbackReasoningEffort: '', chatMode: '', agent: '', bare: '',
      systemPrompt: '', workDir: cwd, conversationKey: '', persistent: '', conversationId: '', env: {},
    },
  };
}

describe('instruction compatibility', () => {
  test('generates one Codex and Pi override while preserving project instructions', () => {
    const context = fixture();
    writeFileSync(
      join(context.cwd, 'AGENTS.md'),
      '# Project Instructions\n\nKeep existing project guidance.\n',
    );
    writeFileSync(
      join(context.env.HOME, '.agent', 'rules', '00-box.md'),
      '---\ntrigger: always_on\n---\n# Box Rule\n\nBox body.\n',
    );
    writeFileSync(
      join(context.cwd, '.agent', 'rules', '01-project.md'),
      '---\ntrigger: model_decision\ndescription: "Use for APIs: preserve contracts."\n---\nHidden body.\n',
    );
    generateAgentOverrides(context);
    generateOmpAlwaysRule(context);

    const override = readFileSync(join(context.cwd, 'AGENTS.override.md'), 'utf8');
    expect(existsSync(join(context.cwd, '.pi', 'SYSTEM.md'))).toBe(false);
    expect(override).toContain('# Project Instructions\n\nKeep existing project guidance.');
    expect(override).toContain('# Box Rule\n\nBox body.');
    expect(override).toContain(
      '- [Use for APIs: preserve contracts.](.agent/rules/01-project.md)',
    );
    expect(override).not.toContain('Hidden body.');
    const omp = readFileSync(
      join(context.cwd, '.omp', 'rules', 'carapa-always-on.md'),
      'utf8',
    );
    expect(omp).toContain('alwaysApply: true');
    expect(omp).toContain('Box body.');
    expect(omp).not.toContain('Use for APIs');
  });

  test('skips a dangling rule link and still generates the remaining rules', () => {
    const context = fixture();
    const rules = join(context.env.HOME, '.agent', 'rules');
    writeFileSync(join(rules, '00-box.md'), '---\ntrigger: always_on\n---\nBox body.\n');
    symlinkSync(join(context.cwd, 'gone.md'), join(rules, 'gone.md'));
    symlinkSync(join(context.cwd, 'gone.md'), join(context.cwd, '.agent', 'rules', 'gone-project.md'));
    generateAgentOverrides(context);
    generateOmpAlwaysRule(context);
    expect(readFileSync(join(context.cwd, 'AGENTS.override.md'), 'utf8')).toContain('Box body.');
    expect(readFileSync(join(context.cwd, '.omp', 'rules', 'carapa-always-on.md'), 'utf8')).toContain('Box body.');
  });

  test('removes only stale generated Pi system prompts', () => {
    const generated = fixture();
    mkdirSync(join(generated.cwd, '.pi'), { recursive: true });
    writeFileSync(
      join(generated.cwd, '.pi', 'SYSTEM.md'),
      '<!-- Generated by CarapaBot from .agent/rules. Do not edit. -->\n# Agent Rules\n',
    );
    generateAgentOverrides(generated);
    expect(existsSync(join(generated.cwd, '.pi', 'SYSTEM.md'))).toBe(false);

    const userAuthored = fixture();
    mkdirSync(join(userAuthored.cwd, '.pi'), { recursive: true });
    writeFileSync(join(userAuthored.cwd, '.pi', 'SYSTEM.md'), 'Custom Pi system prompt.\n');
    generateAgentOverrides(userAuthored);
    expect(readFileSync(join(userAuthored.cwd, '.pi', 'SYSTEM.md'), 'utf8')).toBe(
      'Custom Pi system prompt.\n',
    );
  });

  test('refuses to overwrite a user-authored AGENTS.override.md', () => {
    const context = fixture();
    writeFileSync(
      join(context.cwd, '.agent', 'rules', 'always.md'),
      '---\ntrigger: always_on\n---\nManaged rule.\n',
    );
    writeFileSync(join(context.cwd, 'AGENTS.override.md'), 'User override.\n');
    mkdirSync(join(context.cwd, '.pi'), { recursive: true });
    writeFileSync(
      join(context.cwd, '.pi', 'SYSTEM.md'),
      '<!-- Generated by CarapaBot from .agent/rules. Do not edit. -->\n# Agent Rules\n',
    );

    expect(() => generateAgentOverrides(context)).toThrow(
      'Refusing to overwrite user-authored instruction file',
    );
    expect(readFileSync(join(context.cwd, 'AGENTS.override.md'), 'utf8')).toBe(
      'User override.\n',
    );
    expect(existsSync(join(context.cwd, '.pi', 'SYSTEM.md'))).toBe(false);

    rmSync(join(context.cwd, '.agent', 'rules', 'always.md'));
    writeFileSync(join(context.cwd, 'AGENTS.override.md'), '# Agent Rules\n\nUser content.\n');
    generateAgentOverrides(context);
    expect(readFileSync(join(context.cwd, 'AGENTS.override.md'), 'utf8')).toBe(
      '# Agent Rules\n\nUser content.\n',
    );
  });

  test('repairs a broken legacy skill alias without replacing real directories', () => {
    const context = fixture();
    mkdirSync(join(context.cwd, '.agents'), { recursive: true });
    symlinkSync('.agent/skills', join(context.cwd, '.agents', 'skills'));
    ensureAgentSkillLinks(context);
    expect(readlinkSync(join(context.cwd, '.agents', 'skills'))).toBe('../.agent/skills');
    expect(existsSync(join(context.cwd, '.agent', 'skills'))).toBe(true);
  });
});

describe('group rule layer', () => {
  function groupRule(context: RunContext, name: string, body: string): string {
    const directory = join(context.env.CARAPA_GROUP_ROOT, '.agent', 'rules');
    mkdirSync(directory, { recursive: true });
    const path = join(directory, name);
    writeFileSync(path, `---\ntrigger: always_on\n---\n${body}\n`);
    return path;
  }

  test('adds group rules between home and cwd rules in the override', () => {
    const context = fixture();
    writeFileSync(join(context.env.HOME, '.agent', 'rules', 'a.md'), '---\ntrigger: always_on\n---\nHome body.\n');
    groupRule(context, 'b.md', 'Group body.');
    writeFileSync(join(context.cwd, '.agent', 'rules', 'c.md'), '---\ntrigger: always_on\n---\nRepo body.\n');
    generateAgentOverrides(context);
    const override = readFileSync(join(context.cwd, 'AGENTS.override.md'), 'utf8');
    const order = ['Home body.', 'Group body.', 'Repo body.'].map((text) => override.indexOf(text));
    expect(order.every((index) => index >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  test('a deeper layer replaces a same-named rule', () => {
    const context = fixture();
    writeFileSync(join(context.env.HOME, '.agent', 'rules', 'shared.md'), '---\ntrigger: always_on\n---\nHome version.\n');
    groupRule(context, 'shared.md', 'Group version.');
    generateAgentOverrides(context);
    const override = readFileSync(join(context.cwd, 'AGENTS.override.md'), 'utf8');
    expect(override).toContain('Group version.');
    expect(override).not.toContain('Home version.');
  });

  test('does not repeat group rules when cwd is the group directory', () => {
    const context = fixture();
    context.cwd = context.env.CARAPA_GROUP_ROOT;
    groupRule(context, 'g.md', 'Group once.');
    generateAgentOverrides(context);
    const override = readFileSync(join(context.cwd, 'AGENTS.override.md'), 'utf8');
    expect(override.split('Group once.').length - 1).toBe(1);
  });

  test('Claude gets a stable group rules file only outside the group directory and agent view', () => {
    const context = fixture();
    expect(claudeGroupRulesFile(context)).toBe('');
    groupRule(context, 'g.md', 'Group for Claude.');
    const first = claudeGroupRulesFile(context);
    expect(readFileSync(first, 'utf8')).toContain('Group for Claude.');
    expect(claudeGroupRulesFile(context)).toBe(first);
    const objective = join(context.env.CARAPA_GROUP_ROOT, 'objectives', 'obj-1');
    mkdirSync(objective, { recursive: true });
    expect(claudeGroupRulesFile({ ...context, cwd: objective })).toBe('');
    writeFileSync(join(context.env.HOME, '.agent', 'rules', '.carapa-agent-view'), '');
    expect(claudeGroupRulesFile(context)).toBe('');
  });

  test('keeps the generated override out of git status', () => {
    const context = fixture();
    spawnSync('git', ['init', '-q', context.cwd]);
    groupRule(context, 'g.md', 'Group body.');
    generateAgentOverrides(context);
    generateAgentOverrides(context);
    const status = spawnSync('git', ['-C', context.cwd, 'status', '--porcelain', '--untracked-files=all'], { encoding: 'utf8' });
    expect(status.stdout).not.toContain('AGENTS.override.md');
    const exclude = readFileSync(join(context.cwd, '.git', 'info', 'exclude'), 'utf8');
    expect(exclude.split('/AGENTS.override.md').length - 1).toBe(1);
  });

  test('keeps the generated override out of git status when cwd is below the repo root', () => {
    const context = fixture();
    const repo = context.cwd;
    spawnSync('git', ['init', '-q', repo]);
    const nested = join(repo, 'objectives', 'o[1]');
    mkdirSync(nested, { recursive: true });
    groupRule(context, 'g.md', 'Group body.');
    const nestedContext = { ...context, cwd: nested };
    generateAgentOverrides(nestedContext);
    generateAgentOverrides(nestedContext);
    expect(existsSync(join(nested, 'AGENTS.override.md'))).toBe(true);
    const status = spawnSync('git', ['-C', repo, 'status', '--porcelain', '--untracked-files=all'], { encoding: 'utf8' });
    expect(status.stdout).not.toContain('AGENTS.override.md');
    const exclude = readFileSync(join(repo, '.git', 'info', 'exclude'), 'utf8');
    expect(exclude.split('AGENTS.override.md').length - 1).toBe(1);
  });

  test('keeps the generated OMP rule out of git status', () => {
    const context = fixture();
    spawnSync('git', ['init', '-q', context.cwd]);
    groupRule(context, 'g.md', 'Group body.');
    generateOmpAlwaysRule(context);
    generateOmpAlwaysRule(context);
    expect(existsSync(join(context.cwd, '.omp', 'rules', 'carapa-always-on.md'))).toBe(true);
    const status = spawnSync('git', ['-C', context.cwd, 'status', '--porcelain', '--untracked-files=all'], { encoding: 'utf8' });
    expect(status.stdout).not.toContain('.omp');
    const exclude = readFileSync(join(context.cwd, '.git', 'info', 'exclude'), 'utf8');
    expect(exclude.split('/.omp/rules/carapa-always-on.md').length - 1).toBe(1);
  });
});

describe('model_decision rules excluded from native loading', () => {
  const decision = (description: string, body = 'Reference body.') =>
    `---\ntrigger: model_decision\n${description ? `description: ${description}\n` : ''}---\n${body}\n`;

  function write(directory: string, name: string, content: string): string {
    mkdirSync(directory, { recursive: true });
    const path = join(directory, name);
    writeFileSync(path, content);
    return path;
  }

  function setup() {
    const context = fixture();
    const group = context.env.CARAPA_GROUP_ROOT;
    const store = join(dirname(context.env.HOME), 'store');
    const homeReal = write(store, 'home-ref.md', decision('Home reference'));
    symlinkSync(homeReal, join(context.env.HOME, '.agent', 'rules', 'home-ref.md'));
    const groupReal = write(join(group, '.agent', 'rules'), 'shared.md', decision('Group shared'));
    write(join(group, '.agent', 'rules'), 'group-ref.md', decision('Group reference'));
    write(join(group, '.agent', 'rules'), 'always.md', '---\ntrigger: always_on\n---\nAlways body text.\n');
    write(join(group, '.agent', 'rules'), 'no-description.md', decision(''));
    write(join(group, '.agent', 'rules'), 'plain.md', '# no frontmatter\n');
    write(join(group, '.agent', 'rules'), 'manual.md', '---\ntrigger: manual\ndescription: Manual one\n---\nx\n');
    // A dangling link must be skipped, not fatal.
    mkdirSync(join(group, '.claude', 'rules'), { recursive: true });
    symlinkSync(join(store, 'missing.md'), join(group, '.claude', 'rules', 'dangling.md'));
    return { context, group, homeReal, groupReal, repo: context.cwd };
  }

  const excludes = (settingsFile: string): string[] => JSON.parse(readFileSync(settingsFile, 'utf8')).claudeMdExcludes;

  test('in-group run excludes realpaths of described model_decision rules from every layer, including a shadowed one', () => {
    const { context, group, homeReal, groupReal } = setup();
    const inGroup = { ...context, cwd: join(group, 'objectives', 'o1') };
    // The shadowing rule lives in the objective folder, deeper than the group layer.
    const shadow = write(join(inGroup.cwd, '.claude', 'rules'), 'shared.md', decision('Objective shared'));
    const files = claudeModelDecisionFiles(inGroup)!;
    expect(excludes(files.settingsFile)).toEqual([
      realpathSync(groupReal), realpathSync(join(group, '.agent', 'rules', 'group-ref.md')), realpathSync(homeReal), realpathSync(shadow),
    ].sort());
  });

  test('the index lists only the winning model_decision rules and carries no always_on body', () => {
    const { context, group } = setup();
    const inGroup = { ...context, cwd: join(group, 'objectives', 'o1') };
    write(join(inGroup.cwd, '.claude', 'rules'), 'shared.md', decision('Objective shared'));
    const index = readFileSync(claudeModelDecisionFiles(inGroup)!.indexFile, 'utf8');
    expect(index).toContain('Rules available on model decision');
    expect(index).toContain('[Objective shared]');
    expect(index).toContain('[Group reference]');
    expect(index).toContain('[Home reference]');
    expect(index).not.toContain('[Group shared]');
    expect(index).not.toContain('Always body text.');
    expect(index).not.toContain('Reference body.');
  });

  test('a deeper same-name rule with another trigger, or none, drops the entry from the index but not the exclude', () => {
    const context = fixture();
    const group = context.env.CARAPA_GROUP_ROOT;
    const objective = join(group, 'objectives', 'o1');
    const x = write(join(group, '.agent', 'rules'), 'x.md', decision('Group x'));
    const y = write(join(group, '.agent', 'rules'), 'y.md', decision('Group y'));
    write(join(group, '.agent', 'rules'), 'z.md', decision('Group z'));
    write(join(objective, '.agent', 'rules'), 'x.md', '---\ntrigger: always_on\n---\nObjective x.\n');
    write(join(objective, '.agent', 'rules'), 'y.md', '# no frontmatter\n');
    const files = claudeModelDecisionFiles({ ...context, cwd: objective })!;
    expect(excludes(files.settingsFile)).toContain(realpathSync(x));
    expect(excludes(files.settingsFile)).toContain(realpathSync(y));
    const index = readFileSync(files.indexFile, 'utf8');
    expect(index).not.toContain('[Group x]');
    expect(index).not.toContain('[Group y]');
    expect(index).toContain('[Group z]');
  });

  test('every indexed rule shadowed by a non-model_decision rule: excludes stay, no index file', () => {
    const context = fixture();
    const group = context.env.CARAPA_GROUP_ROOT;
    const objective = join(group, 'objectives', 'o1');
    const x = write(join(group, '.agent', 'rules'), 'x.md', decision('Group x'));
    write(join(objective, '.agent', 'rules'), 'x.md', '---\ntrigger: always_on\n---\nObjective x.\n');
    const files = claudeModelDecisionFiles({ ...context, cwd: objective })!;
    expect(excludes(files.settingsFile)).toEqual([realpathSync(x)]);
    expect(files.indexFile).toBe('');
  });

  test('an agent-view run outside the group gets the same settings; paths are stable', () => {
    const { context, repo, groupReal } = setup();
    const outside = { ...context, cwd: repo };
    expect(claudeModelDecisionFiles(outside)).toBeNull();
    writeFileSync(join(context.env.HOME, '.agent', 'rules', '.carapa-agent-view'), '');
    const first = claudeModelDecisionFiles(outside)!;
    expect(excludes(first.settingsFile)).toContain(realpathSync(groupReal));
    expect(claudeModelDecisionFiles(outside)).toEqual(first);
    write(join(context.env.CARAPA_GROUP_ROOT, '.agent', 'rules'), 'new-ref.md', decision('Another'));
    expect(claudeModelDecisionFiles(outside)!.settingsFile).not.toBe(first.settingsFile);
  });

  test('rules in nested folders and in ancestor directories of cwd are excluded and indexed', () => {
    const context = fixture();
    const group = context.env.CARAPA_GROUP_ROOT;
    const objective = join(group, 'objectives', 'one');
    const nested = write(join(group, '.claude', 'rules', 'references'), 'ref.md', decision('Nested group reference'));
    const ancestor = write(join(objective, '.claude', 'rules'), 'ref.md', decision('Objective reference'));
    // A symlinked folder pointing back at its parent must not loop.
    symlinkSync(join(group, '.claude', 'rules'), join(group, '.claude', 'rules', 'loop'));
    const files = claudeModelDecisionFiles({ ...context, cwd: join(objective, 'src') })!;
    expect(excludes(files.settingsFile)).toEqual([realpathSync(nested), realpathSync(ancestor)].sort());
    const index = readFileSync(files.indexFile, 'utf8');
    expect(index).toContain('[Nested group reference]');
    expect(index).toContain('[Objective reference]');
  });

  test('a rule in the group directory replaces a same-named rule in an ancestor above it in the index', () => {
    const context = fixture();
    const parent = dirname(context.env.CARAPA_GROUP_ROOT);
    const above = write(join(parent, '.claude', 'rules'), 'ref.md', decision('Parent reference'));
    const inGroup = write(join(context.env.CARAPA_GROUP_ROOT, '.claude', 'rules'), 'ref.md', decision('Group reference'));
    const files = claudeModelDecisionFiles({ ...context, cwd: context.env.CARAPA_GROUP_ROOT })!;
    expect(excludes(files.settingsFile)).toEqual([realpathSync(above), realpathSync(inGroup)].sort());
    const index = readFileSync(files.indexFile, 'utf8');
    expect(index).toContain('[Group reference]');
    expect(index).not.toContain('[Parent reference]');
  });

  test('exclusion entries are literal paths: glob characters in a file name do not catch siblings', () => {
    const context = fixture();
    const directory = join(context.env.CARAPA_GROUP_ROOT, '.agent', 'rules');
    const eligible = write(directory, 'ref[ab].md', decision('Bracket reference'));
    write(directory, 'refa.md', '---\ntrigger: always_on\n---\nSibling body.\n');
    context.cwd = context.env.CARAPA_GROUP_ROOT;
    const [entry, ...rest] = excludes(claudeModelDecisionFiles(context)!.settingsFile);
    expect(rest).toEqual([]);
    expect(entry).toBe(`${directory}/ref\\[ab\\].md`);
    expect(realpathSync(eligible)).toBe(eligible);
  });

  test('no eligible rule gives no files', () => {
    const context = fixture();
    context.cwd = context.env.CARAPA_GROUP_ROOT;
    write(join(context.cwd, '.agent', 'rules'), 'a.md', decision(''));
    write(join(context.cwd, '.agent', 'rules'), 'b.md', '---\ntrigger: always_on\n---\nB\n');
    expect(claudeModelDecisionFiles(context)).toBeNull();
  });
});
