interface Rule {
  path: string;
  link: string;
  trigger: string;
  description: string;
  body: string;
}

const OVERRIDE_MARKER = '<!-- Generated by CarapaBot from .agent/rules. Do not edit. -->';
const OMP_MARKER = '<!-- Generated by CarapaBot from trigger: always_on rules. Do not edit. -->';

function parseRule(path: string, link: string): Rule | null {
  const raw = readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
  const lines = raw.split('\n');
  if (lines[0] !== '---') return null;
  const closing = lines.indexOf('---', 1);
  if (closing < 0) return null;
  const metadata: Record<string, string> = {};
  for (const line of lines.slice(1, closing)) {
    const match = line.match(/^\s*([A-Za-z0-9_-]+):\s*(.*?)\s*$/);
    if (!match) continue;
    let value = match[2];
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    metadata[match[1]] = value;
  }
  return {
    path,
    link,
    trigger: metadata.trigger ?? '',
    description: metadata.description ?? '',
    body: lines.slice(closing + 1).join('\n').replace(/^\n+|\n+$/g, ''),
  };
}

/** Project group directory: fixed in a sandbox, mapped by CARAPA_GROUP_ROOT for a native runner. */
function groupRoot(context: RunContext): string {
  return resolve(context.env.CARAPA_GROUP_ROOT || '/workspace/group');
}

/** True when cwd is the group directory or inside it (group chat, objective runs). */
function insideGroup(context: RunContext): boolean {
  const group = groupRoot(context);
  const cwd = resolve(context.cwd);
  return cwd === group || cwd.startsWith(group + sep);
}

function readLayer(directory: string, link: (path: string) => string): Rule[] {
  if (!existsSync(directory)) return [];
  const result: Rule[] = [];
  for (const name of readdirSync(directory).filter((item) => item.endsWith('.md')).sort()) {
    const path = join(directory, name);
    let parsed: Rule | null;
    try {
      parsed = parseRule(path, link(path));
    } catch {
      continue; // Dangling link or unreadable file: skip it, as the native rule scan does.
    }
    if (parsed) result.push(parsed);
  }
  return result;
}

/**
 * Rule layers in a fixed order: agent home, project group, then cwd (an
 * objective folder or a repository). A deeper layer's file replaces a
 * shallower file with the same name.
 */
function rules(context: RunContext): Rule[] {
  const homeRules = join(context.env.HOME || '/home/ubuntu', '.agent', 'rules');
  const groupRules = join(groupRoot(context), '.agent', 'rules');
  const workspaceRules = join(context.cwd, '.agent', 'rules');
  const layers = [readLayer(homeRules, (path) => path)];
  if (resolve(groupRules) !== resolve(workspaceRules)) layers.push(readLayer(groupRules, (path) => path));
  layers.push(readLayer(workspaceRules, (path) => relative(context.cwd, path)));
  const byName = new Map<string, Rule>();
  for (const layer of layers) {
    for (const rule of layer) {
      // Re-insert so the replacing rule keeps its deeper layer's position.
      byName.delete(basename(rule.path));
      byName.set(basename(rule.path), rule);
    }
  }
  return [...byName.values()];
}

function isModelDecision(rule: Rule): boolean {
  return rule.trigger === 'model_decision' && Boolean(rule.description);
}

/** Link list of the rules the model opens on demand. Empty when there are none. */
function renderRuleIndex(eligible: Rule[]): string[] {
  const conditional = eligible.filter(isModelDecision);
  if (conditional.length === 0) return [];
  const lines = ['## Rules available on model decision', ''];
  for (const rule of conditional) {
    const description = rule.description.replaceAll('\\', '\\\\').replaceAll(']', '\\]');
    lines.push(`- [${description}](${rule.link})`);
  }
  return lines;
}

function renderRules(eligible: Rule[]): string[] {
  const lines = ['# Agent Rules', ''];
  for (const rule of eligible.filter((item) => item.trigger === 'always_on')) {
    lines.push(rule.body, '');
  }
  lines.push(...renderRuleIndex(eligible));
  return lines;
}

function eligibleRules(list: Rule[]): Rule[] {
  return list.filter(
    (rule) =>
      rule.trigger === 'always_on' ||
      isModelDecision(rule),
  );
}

/** Keep a generated file out of git status without changing the repository. */
function excludeFromGit(cwd: string, name: string): void {
  const result = spawnSync('git', ['-C', cwd, 'rev-parse', '--git-path', 'info/exclude', '--show-prefix'], { encoding: 'utf8' });
  if (result.status !== 0) return;
  const [excludePath = '', prefix = ''] = result.stdout.split(/\r?\n/);
  const exclude = resolve(cwd, excludePath);
  // info/exclude patterns are anchored at the repository top level, so a run below it needs its prefix.
  const entry = `/${prefix.replace(/[\\*?[\]]/g, '\\$&')}${name}`;
  const current = existsSync(exclude) ? readFileSync(exclude, 'utf8') : '';
  if (current.split(/\r?\n/).includes(entry)) return;
  mkdirSync(dirname(exclude), { recursive: true });
  writeFileSync(exclude, `${current}${current && !current.endsWith('\n') ? '\n' : ''}${entry}\n`);
}

function firstLine(path: string): string {
  if (!existsSync(path)) return '';
  return readFileSync(path, 'utf8').split(/\r?\n/, 1)[0] ?? '';
}

function removeGeneratedOverride(path: string): void {
  if (firstLine(path) === OVERRIDE_MARKER) rmSync(path, { force: true });
}

function writeOverride(path: string, eligible: Rule[], projectInstructions: string): void {
  if (eligible.length === 0) {
    removeGeneratedOverride(path);
    return;
  }
  if (existsSync(path) && firstLine(path) !== OVERRIDE_MARKER) {
    throw new Error(`Refusing to overwrite user-authored instruction file: ${path}`);
  }
  const lines = [OVERRIDE_MARKER];
  const projectBody = projectInstructions.replace(/^\s+|\s+$/g, '');
  if (projectBody) {
    lines.push(
      '<!-- Included because AGENTS.override.md takes precedence over AGENTS.md. -->',
      '',
      projectBody,
      '',
    );
  }
  lines.push(...renderRules(eligible));
  mkdirSync(dirname(path), { recursive: true });
  atomicWrite(path, `${lines.join('\n').replace(/\n+$/, '')}\n`);
  excludeFromGit(dirname(path), 'AGENTS.override.md');
}

export function generateAgentOverrides(context: RunContext): void {
  const eligible = eligibleRules(rules(context));
  removeGeneratedOverride(join(context.cwd, '.pi', 'SYSTEM.md'));
  const projectInstructionsPath = join(context.cwd, 'AGENTS.md');
  const projectInstructions = eligible.length > 0 && existsSync(projectInstructionsPath)
    ? readFileSync(projectInstructionsPath, 'utf8')
    : '';
  writeOverride(join(context.cwd, 'AGENTS.override.md'), eligible, projectInstructions);
}

export function generateOmpAlwaysRule(context: RunContext): void {
  const target = join(context.cwd, '.omp', 'rules', 'carapa-always-on.md');
  const always = rules(context).filter((rule) => rule.trigger === 'always_on');
  if (always.length === 0) {
    if (existsSync(target) && readFileSync(target, 'utf8').split(/\r?\n/)[3] === OMP_MARKER) {
      rmSync(target, { force: true });
    }
    return;
  }
  if (existsSync(target) && readFileSync(target, 'utf8').split(/\r?\n/)[3] !== OMP_MARKER) return;
  const content = [
    '---',
    'alwaysApply: true',
    '---',
    OMP_MARKER,
    '# Carapa Always-On Rules',
    '',
    ...always.flatMap((rule) => [rule.body, '']),
  ];
  mkdirSync(dirname(target), { recursive: true });
  atomicWrite(target, `${content.join('\n').replace(/\n+$/, '')}\n`);
  excludeFromGit(context.cwd, '.omp/rules/carapa-always-on.md');
}

export function ensureAgentSkillLinks(context: RunContext): void {
  const canonical = join(context.cwd, '.agent', 'skills');
  const agents = join(context.cwd, '.agents');
  const alias = join(agents, 'skills');
  mkdirSync(canonical, { recursive: true });
  mkdirSync(agents, { recursive: true });
  let aliasExists = false;
  try {
    aliasExists = lstatSync(alias).isSymbolicLink() || existsSync(alias);
  } catch {
    aliasExists = false;
  }
  if (aliasExists && lstatSync(alias).isSymbolicLink()) {
    if (readlinkSync(alias) !== '../.agent/skills') {
      rmSync(alias);
      symlinkSync('../.agent/skills', alias);
    }
  } else if (!aliasExists) {
    symlinkSync('../.agent/skills', alias);
  }
}

export function prepareCodexHome(context: RunContext, target: string): void {
  const seed = context.env.CARAPA_CODEX_SEED_HOME || join(context.env.HOME || '/home/ubuntu', '.codex');
  if (target === seed) return;
  mkdirSync(target, { recursive: true, mode: 0o700 });
  if (!existsSync(seed)) return;
  const configNames = readdirSync(seed).filter(
    (name) => name === 'config.toml' || name.endsWith('.config.toml'),
  );
  // A native runner reaches the relay and llama-proxy at its local forwarder.
  for (const name of configNames) {
    writeFileSync(join(target, name), hostUrlsInText(readFileSync(join(seed, name), 'utf8'), context.env), { mode: 0o600 });
  }
  for (const name of ['installation_id', 'models_cache.json']) {
    const source = join(seed, name);
    const destination = join(target, name);
    if (existsSync(source) && !existsSync(destination)) copyFileSync(source, destination);
  }
  for (const name of ['rules', 'skills']) {
    const source = join(seed, name);
    const destination = join(target, name);
    if (existsSync(source) && !existsSync(destination)) symlinkSync(source, destination);
  }
}

/**
 * Group rules for Claude. Claude loads ~/.claude/rules and .claude/rules from
 * cwd and its parent directories itself, so only a run outside the group
 * directory (a repository checkout) misses them. Returns a content-addressed
 * file for --append-system-prompt-file (stable path, so persistent sessions are
 * not restarted while the rules are unchanged), or '' when nothing is missing.
 * A container agent view already links the group rules into ~/.claude/rules.
 */
export function claudeGroupRulesFile(context: RunContext): string {
  if (insideGroup(context) || agentViewActive(context.env.HOME || '/home/ubuntu')) return '';
  const directory = join(groupRoot(context), '.agent', 'rules');
  const eligible = eligibleRules(readLayer(directory, (path) => path));
  if (eligible.length === 0) return '';
  const content = `${['<!-- Project group rules (' + directory + '), added by CarapaBot. -->', '', ...renderRules(eligible)].join('\n').replace(/\n+$/, '')}\n`;
  return cacheFile(context, 'group-rules', 'md', content);
}

/** Write a content-addressed file under ~/.cache/carapa; the same content gives the same path. */
function cacheFile(context: RunContext, prefix: string, extension: string, content: string): string {
  const hash = createHash('sha256').update(content).digest('hex').slice(0, 16);
  const target = join(context.env.HOME || '/home/ubuntu', '.cache', 'carapa', `${prefix}-${hash}.${extension}`);
  if (!existsSync(target)) {
    mkdirSync(dirname(target), { recursive: true });
    atomicWrite(target, content);
  }
  return target;
}

/** Markdown files under a rules directory, nested folders included (Claude loads those too). */
function ruleFiles(directory: string, seen = new Set<string>()): string[] {
  let names: string[];
  try {
    const real = realpathSync(directory);
    if (seen.has(real)) return [];
    seen.add(real);
    names = readdirSync(directory).sort();
  } catch {
    return [];
  }
  const files: string[] = [];
  for (const name of names) {
    const path = join(directory, name);
    try {
      if (statSync(path).isDirectory()) files.push(...ruleFiles(path, seen));
      else if (name.endsWith('.md')) files.push(path);
    } catch { /* Dangling link: nothing to exclude. */ }
  }
  return files;
}

/**
 * Every rule file Claude loads natively, from all layers and before same-name
 * shadowing (Claude still loads a shadowed file). `rule` is null for a file
 * without frontmatter; it still takes part in same-name precedence. Claude reads `.claude/rules` (a view or link over `.agent/rules`) in
 * the home, in cwd and in each of its ancestors, nested folders included. The
 * home, group and cwd layers also scan `.agent/rules`. Unreadable files are
 * skipped. `key` is the path inside its rules directory, the same-name identity.
 */
function nativeRules(context: RunContext): Array<{ rule: Rule | null; real: string; key: string }> {
  const ancestors: string[] = [];
  for (let directory = resolve(context.cwd); !ancestors.includes(directory); directory = dirname(directory)) {
    ancestors.unshift(directory);
  }
  // Shallow to deep: home, then the ancestors of cwd from the root down. The group
  // takes its place in that chain, or follows home when cwd is outside it.
  const group = groupRoot(context);
  const chain = ancestors.includes(group) ? ancestors : [group, ...ancestors];
  const directories = new Set<string>();
  for (const root of [context.env.HOME || '/home/ubuntu', ...chain]) {
    directories.add(join(root, '.agent', 'rules'));
    directories.add(join(root, '.claude', 'rules'));
  }
  const found: Array<{ rule: Rule | null; real: string; key: string }> = [];
  for (const directory of directories) {
    for (const path of ruleFiles(directory)) {
      try {
        found.push({ rule: parseRule(path, path), real: realpathSync(path), key: relative(directory, path) });
      } catch { /* Unreadable: Claude cannot load it either. */ }
    }
  }
  return found;
}

/** `claudeMdExcludes` entries are picomatch globs: escape a path so it matches only itself. */
function globLiteral(path: string): string {
  return path.replace(/[\\*?[\]{}()!+@|]/g, '\\$&');
}

/**
 * For a Claude run that loads rules natively (inside the group directory, or
 * with the agent view linking them into ~/.claude/rules): a settings file whose
 * `claudeMdExcludes` keeps the model_decision rules out of the context, and an
 * index file linking them instead. Always_on rules stay with Claude's own
 * loading, so the index holds no rule bodies. A model_decision rule that a
 * deeper rule of the same name replaces is excluded but not indexed; when no
 * indexed rule is left, `indexFile` is ''. Both files are content-addressed
 * (stable paths keep persistent sessions warm). Null when the run loads no
 * rules natively or no rule qualifies. Throws when a file cannot be written.
 */
export function claudeModelDecisionFiles(context: RunContext): { settingsFile: string; indexFile: string } | null {
  if (!insideGroup(context) && !agentViewActive(context.env.HOME || '/home/ubuntu')) return null;
  const found = nativeRules(context);
  const excluded = found.filter(({ rule }) => rule && isModelDecision(rule));
  if (excluded.length === 0) return null;
  const excludes = [...new Set(excluded.map(({ real }) => globLiteral(real)))].sort();
  // A deeper layer's same-named rule replaces a shallower one in the index, even
  // when both resolve to files that are excluded or the deeper one is not a
  // model_decision rule.
  const byName = new Map<string, { rule: Rule | null; real: string }>();
  for (const { rule, real, key } of found) {
    byName.delete(key);
    byName.set(key, { rule, real });
  }
  const indexed = new Map<string, Rule>();
  for (const { rule, real } of byName.values()) if (rule && isModelDecision(rule) && !indexed.has(real)) indexed.set(real, rule);
  const index = renderRuleIndex([...indexed.values()]);
  const indexContent = `${['<!-- Rules loaded on demand, indexed by CarapaBot. -->', '', ...index].join('\n')}\n`;
  return {
    settingsFile: cacheFile(context, 'claude-settings', 'json', `${JSON.stringify({ claudeMdExcludes: excludes }, null, 2)}\n`),
    indexFile: index.length ? cacheFile(context, 'rules-index', 'md', indexContent) : '',
  };
}
